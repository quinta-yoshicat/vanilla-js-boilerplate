let currentLang = (state.lang && TRANSLATIONS[state.lang]) ? state.lang : 'pt';

function t(key) {
  const dict = TRANSLATIONS[currentLang] || TRANSLATIONS.pt;
  return dict[key] !== undefined ? dict[key] : (TRANSLATIONS.pt[key] !== undefined ? TRANSLATIONS.pt[key] : key);
}

// Texto que vem DENTRO de uma entrada de dados ({ pt, en, es }, como as visitas):
// no idioma atual, com o português como reserva. Usado por níveis, capítulos e
// histórias quando a entrada traz o texto em vez de uma chave deste ficheiro.
function textoNaLingua(texto) {
  if (!texto || typeof texto !== 'object') return '';
  return texto[currentLang] || texto.pt || '';
}

// Texto de conteúdo (nome de nível, título e objetivo de capítulo, texto de objetivo...) para meter
// em HTML montado por concatenação (innerHTML): troca & < > " ' pelas entidades, para que um texto
// vindo de dados/ nunca parte o cartão. Só se usa na hora de montar o HTML, e uma só vez por texto:
// o que vai para textContent (balões de fala, mostrarFalas) já é seguro e NÃO se escapa.
function escaparHtml(texto) {
  return String(texto).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&#39;');
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(function (el) {
    el.textContent = t(el.getAttribute('data-i18n'));
  });
  document.querySelectorAll('[data-i18n-aria]').forEach(function (el) {
    el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria')));
  });
  document.querySelectorAll('[data-i18n-title]').forEach(function (el) {
    el.setAttribute('title', t(el.getAttribute('data-i18n-title')));
  });
}

const LOCALE_DO_IDIOMA = { pt: 'pt-PT', en: 'en-GB', es: 'es-ES' };

function localeAtual() {
  return LOCALE_DO_IDIOMA[currentLang] || 'pt-PT';
}

function setLanguage(lang) {
  if (!TRANSLATIONS[lang]) return;
  currentLang = lang;
  state.lang = lang;
  saveState(state);
  applyTranslations();
  // Nomes com tamanhos diferentes por língua podem mudar se uma fila de
  // pastilhas (ver js/main.js) ainda cabe toda ou passa a precisar de setas.
  if (typeof atualizarTodasAsFilasDePastilhas === 'function') atualizarTodasAsFilasDePastilhas();
}

function selecionarLingua(lang) {
  setLanguage(lang);
  showMessage(t('lingua.confirmado'));
  goTo('home');
}

function renderLinguaScreen() {
  applyTranslations();
}
